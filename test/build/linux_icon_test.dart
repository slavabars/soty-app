import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';

/// Regression guard for the Linux desktop build shipping no icon.
///
/// The stock Flutter GTK runner never sets a window icon and cannot offer a
/// tray icon, so on Linux the window and the system tray showed a blank
/// placeholder. The runner reads `assets/soty_icon.png` out of
/// `data/flutter_assets/` (a regular Flutter asset, declared in pubspec) and
/// uses it both for the window icon (`gtk_window_set_icon_from_file`) and for
/// the `GtkStatusIcon` tray entry.
void main() {
  group('linux desktop icon', () {
    test('the generated icon asset is a 256x256 PNG', () {
      final icon = File('assets/soty_icon.png');
      expect(icon.existsSync(), isTrue,
          reason: 'assets/soty_icon.png is generated by '
              'tool/generate_icons.py and must be committed');
      final bytes = icon.readAsBytesSync();
      expect(bytes.length, greaterThan(8));
      expect(bytes.sublist(0, 4), [0x89, 0x50, 0x4E, 0x47]);
      final data = ByteData.sublistView(bytes);
      expect(data.getUint32(8), 13, reason: 'first chunk must be IHDR');
      expect(String.fromCharCodes(bytes.sublist(12, 16)), 'IHDR');
      expect(data.getUint32(16), 256, reason: 'window icon width');
      expect(data.getUint32(20), 256, reason: 'window icon height');
      expect(bytes[24], 8, reason: '8-bit channels so GTK can scale it');
    });

    test('pubspec declares the icon so it lands in the bundle', () {
      final pubspec = File('pubspec.yaml').readAsStringSync();
      expect(pubspec, contains('assets/soty_icon.png'));
    });

    test('the GTK runner wires window icon and tray', () {
      final runner = File('linux/runner/my_application.cc').readAsStringSync();
      expect(runner, contains('gtk_window_set_icon_from_file'));
      expect(runner, contains('gtk_status_icon_new_from_pixbuf'));
      expect(runner, contains('G_GNUC_BEGIN_IGNORE_DEPRECATIONS'),
          reason: 'the runner is compiled with -Werror, so deprecated '
              'GtkStatusIcon calls must be wrapped');
    });

    test('a built Linux bundle still ships the icon', () {
      final icon =
          File('../build-artifacts/soty-linux-x64/data/flutter_assets/'
              'assets/soty_icon.png');
      if (!icon.existsSync()) {
        markTestSkipped('no Linux bundle in ../build-artifacts yet');
        return;
      }
      final bytes = icon.readAsBytesSync();
      expect(bytes.sublist(0, 4), [0x89, 0x50, 0x4E, 0x47],
          reason: '${icon.path} must be a real PNG inside the bundle');
    });
  });
}